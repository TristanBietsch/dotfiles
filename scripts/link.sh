#!/usr/bin/env bash
# link.sh — stow every package in this repo into $HOME and wire up layers.
#
#   scripts/link.sh
#
# Base packages are listed below. A layer package is a top-level dir named
# <base>-<layer> (e.g. claude-solana, zsh-solana); it is found automatically,
# so a downstream repo adds a layer just by adding the dir.
#
# Also:
#   - removes broken symlinks in $HOME that point into this repo (moved files)
#   - writes ~/.claude/CLAUDE.layers.md: one @import per claude-<layer>/.claude/CLAUDE.<x>.md
#   - points git hooks at .githooks/
#
# Safe to re-run. If stow finds a real file in $HOME where a link should go,
# it aborts and prints the path: move that file aside and run again.
set -euo pipefail

cd "$(dirname "$0")/.."
REPO=$PWD

# Base packages linked on every platform.
BASE=(
	agy bottom btop claude codex fzf gh ghostty git lsd ncspot nvim
	obsidian opencode rmpc tmux w3m weather yazi zsh
)
# macOS-only window manager and keyboard remapper.
DARWIN=(aerospace karabiner)
[[ $(uname -s) == Darwin ]] && BASE+=("${DARWIN[@]}")

is_base() {
	local b
	for b in "${BASE[@]}" "${DARWIN[@]}"; do [[ $1 == "$b" ]] && return 0; done
	return 1
}

LAYERS=()
for d in */; do
	d=${d%/}
	[[ $d == *-* ]] || continue
	is_base "${d%%-*}" && LAYERS+=("$d")
done

echo "==> Removing broken links into $REPO"
while IFS= read -r l; do
	[[ -e $l ]] && continue
	[[ $(readlink "$l") == *"$REPO"/* || $(readlink "$l") == *"$(basename "$REPO")"/* ]] || continue
	rm -f -- "$l" && echo "  - $l"
done < <(find "$HOME/.claude" "$HOME/.local/bin" "$HOME/.config" "$HOME/.zshrc.d" \
	-path "$HOME/.claude/projects" -prune -o -type l -print 2>/dev/null)

echo "==> Linking packages"
FAILED=()
for pkg in "${BASE[@]}" "${LAYERS[@]}"; do
	[[ -d $pkg ]] || continue
	# Karabiner ignores changes to a symlinked karabiner.json; it needs the
	# whole ~/.config/karabiner directory linked, so let stow fold it.
	fold=--no-folding
	[[ $pkg == karabiner ]] && fold=
	# shellcheck disable=SC2086
	stow -R $fold -t "$HOME" "$pkg" || FAILED+=("$pkg")
done
echo "  layers: ${LAYERS[*]:-none}"

echo "==> Writing ~/.claude/CLAUDE.layers.md"
mkdir -p "$HOME/.claude"
{
	echo "<!-- Generated by $REPO/scripts/link.sh. Do not edit. -->"
	found=0
	for f in claude-*/.claude/CLAUDE.*.md; do
		[[ -f $f ]] || continue
		echo "@~/.claude/$(basename "$f")"
		found=1
	done
	((found)) || echo "No layers installed."
} >"$HOME/.claude/CLAUDE.layers.md"

git config core.hooksPath .githooks
if ((${#FAILED[@]})); then
	echo "==> Linked, except: ${FAILED[*]} (stow conflict above; move the file aside and re-run)"
	exit 1
fi
echo "==> Linked"
