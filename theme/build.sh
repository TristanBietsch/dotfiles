#!/usr/bin/env bash
# build — render the active theme into every app's color file.
#
#   theme/build.sh            build the theme named in theme/active
#   theme/build.sh <name>     switch to themes/<name> and build it
#
# Source of truth: theme/themes/<name>/colors.env
# Templates in theme/templates/ use {{key}}, {{key.rgb}} (hex as r;g;b)
# and {{key.glob}} (space list as a,b,c).
# Outputs land inside the stow packages, so nothing reads theme/ at runtime.

set -euo pipefail

THEME_DIR="$(cd "$(dirname "$0")" && pwd)"
DOTFILES="$(dirname "$THEME_DIR")"

if [ $# -gt 0 ]; then
	echo "$1" > "$THEME_DIR/active"
fi
NAME="$(tr -d '[:space:]' < "$THEME_DIR/active")"
ENV_FILE="$THEME_DIR/themes/$NAME/colors.env"
[ -f "$ENV_FILE" ] || { echo "no such theme: $ENV_FILE" >&2; exit 1; }

# template -> output (relative to dotfiles root)
OUTPUTS=(
	"ghostty:ghostty/.config/ghostty/colors"
	"lsd-colors.yaml:lsd/.config/lsd/colors.yaml"
	"lsd-icons.yaml:lsd/.config/lsd/icons.yaml"
	"ls_colors.zsh:zsh/.config/zsh/ls_colors.zsh"
	"yazi-theme.toml:yazi/.config/yazi/theme.toml"
)

# shellcheck disable=SC1090
source "$ENV_FILE"
KEYS=($(grep -oE '^[a-z0-9_]+=' "$ENV_FILE" | tr -d '='))

rgb() { printf '%d;%d;%d' "0x${1:1:2}" "0x${1:3:2}" "0x${1:5:2}"; }
is_hex() { [[ "$1" =~ ^#[0-9a-fA-F]{6}$ ]]; }

SED="$(mktemp)"
trap 'rm -f "$SED"' EXIT
echo "s|{{theme}}|$NAME|g" > "$SED"
for k in "${KEYS[@]}"; do
	v="${!k}"
	echo "s|{{$k}}|$v|g" >> "$SED"
	if is_hex "$v"; then
		echo "s|{{$k.rgb}}|$(rgb "$v")|g" >> "$SED"
	else
		echo "s|{{$k.glob}}|${v// /,}|g" >> "$SED"
	fi
done

for pair in "${OUTPUTS[@]}"; do
	tmpl="$THEME_DIR/templates/${pair%%:*}"
	out="$DOTFILES/${pair#*:}"
	mkdir -p "$(dirname "$out")"
	sed -f "$SED" "$tmpl" > "$out"
	if grep -q '{{' "$out"; then
		echo "unfilled placeholder in $out:" >&2
		grep -n '{{' "$out" >&2
		exit 1
	fi
	echo "  wrote ${pair#*:}"
done

# nvim palette: every key as a Lua table
lua="$DOTFILES/nvim/.config/nvim/lua/core/palette.lua"
{
	echo "-- generated by theme/build.sh ($NAME). Edit theme/themes/$NAME/colors.env instead."
	echo "return {"
	for k in "${KEYS[@]}"; do echo "  $k = '${!k}',"; done
	echo "}"
} > "$lua"
echo "  wrote nvim/.config/nvim/lua/core/palette.lua"

# colors.css: hex keys as CSS custom properties
css="$THEME_DIR/themes/$NAME/colors.css"
{
	echo "/* generated by theme/build.sh ($NAME). Edit colors.env instead. */"
	echo ":root {"
	for k in "${KEYS[@]}"; do is_hex "${!k}" && echo "  --${k//_/-}: ${!k};"; done
	echo "}"
} > "$css"
echo "  wrote theme/themes/$NAME/colors.css"

# colors.md: one table per "# section" in colors.env
md="$THEME_DIR/themes/$NAME/colors.md"
{
	echo "# $NAME"
	echo
	echo "Generated by \`theme/build.sh\`. Edit \`colors.env\`, then rebuild."
	echo
	header=1
	while IFS= read -r line; do
		if [ -n "$header" ]; then
			# leading comment block: copy as prose, stop at first blank line
			[ -z "$line" ] && { header=""; continue; }
			echo "${line#\# }  "
		elif [[ "$line" =~ ^#\ (.+)$ ]]; then
			printf '\n## %s\n\n| key | value | source |\n|---|---|---|\n' "${BASH_REMATCH[1]}"
		elif [[ "$line" =~ ^([a-z0-9_]+)=(.*)$ ]]; then
			k="${BASH_REMATCH[1]}"
			src="${BASH_REMATCH[2]}"
			[[ "$src" == \$* ]] || src=""
			src="${src//\'/}"
			printf '| `%s` | `%s` | %s |\n' "$k" "${!k}" "${src:+\`$src\`}"
		fi
	done < "$ENV_FILE"
} > "$md"
echo "  wrote theme/themes/$NAME/colors.md"

echo "==> built $NAME"
